/**
 * Driver history module — "Mis movimientos" for the repartidor.
 *
 * Unlike `/admin/informes` (which reports what was *sold* in a period), this
 * endpoint reports what the authenticated repartidor *did*, anchored to the
 * real timestamp of each individual action. That means an order claimed on
 * Monday and delivered on Tuesday produces two entries on two different days,
 * which is what the driver actually experiences.
 *
 * Every operation the repartidor can perform is represented:
 *
 *   ORDER_CLAIMED     - took a PENDING order out of the pool.
 *   DELIVERY_STARTED  - started the route for an order assigned to them.
 *   ORDER_DELIVERED   - closed a full-circuit order (citizen placed it).
 *   DIRECT_ORDER      - registered a sale at the door ("Nueva entrega"),
 *                       born DELIVERED. Collapsed into a single entry.
 *   ORDER_CANCELLED   - an order they held got cancelled.
 *   CASH_COLLECTED    - a cash movement with no attached order (manual).
 *   CASH_REVERSED     - a cash collection was annulled.
 *
 * Money attached to an order is folded into that order's delivery entry
 * (`cashCollectedMinor` / `accountChargedMinor` / `accountReversedMinor`) so
 * the same peso is never counted twice. Only cash movements that are NOT
 * attached to an order become their own timeline entries.
 */
import type { ReportPeriodPreset } from '../reports/reports.types.js';

export const DRIVER_OPERATION_KINDS = {
  ORDER_CLAIMED: 'ORDER_CLAIMED',
  DELIVERY_STARTED: 'DELIVERY_STARTED',
  ORDER_DELIVERED: 'ORDER_DELIVERED',
  DIRECT_ORDER: 'DIRECT_ORDER',
  ORDER_CANCELLED: 'ORDER_CANCELLED',
  CASH_COLLECTED: 'CASH_COLLECTED',
  CASH_REVERSED: 'CASH_REVERSED',
} as const;

export type DriverOperationKind =
  (typeof DRIVER_OPERATION_KINDS)[keyof typeof DRIVER_OPERATION_KINDS];

export const ALL_DRIVER_OPERATION_KINDS: DriverOperationKind[] =
  Object.values(DRIVER_OPERATION_KINDS);

export const DRIVER_OPERATION_LABEL: Record<DriverOperationKind, string> = {
  ORDER_CLAIMED: 'Tomó el pedido',
  DELIVERY_STARTED: 'Inició el reparto',
  ORDER_DELIVERED: 'Entregó el pedido',
  DIRECT_ORDER: 'Nueva entrega',
  ORDER_CANCELLED: 'Pedido cancelado',
  CASH_COLLECTED: 'Cobró en efectivo',
  CASH_REVERSED: 'Revirtió un cobro',
};

/**
 * Operations that settle money. Used by the workbook and the UI to decide
 * whether the "Monto" column is meaningful for a row.
 */
export const DRIVER_SETTLING_KINDS: DriverOperationKind[] = [
  DRIVER_OPERATION_KINDS.ORDER_DELIVERED,
  DRIVER_OPERATION_KINDS.DIRECT_ORDER,
  DRIVER_OPERATION_KINDS.CASH_COLLECTED,
  DRIVER_OPERATION_KINDS.CASH_REVERSED,
];

/** Hard cap on the returned timeline so a wide period can't blow the response. */
export const DRIVER_HISTORY_MAX_OPERATIONS = 500;

// ----------------------------------------------------------------------------
// Filters
// ----------------------------------------------------------------------------

export interface DriverHistoryFilters {
  period: ReportPeriodPreset;
  /** Required when period === 'CUSTOM'. ISO date (YYYY-MM-DD), inclusive. */
  dateFrom?: string;
  /** Required when period === 'CUSTOM'. ISO date (YYYY-MM-DD), inclusive. */
  dateTo?: string;
}

// ----------------------------------------------------------------------------
// Payload
// ----------------------------------------------------------------------------

export interface DriverHistoryItemRow {
  productCode: string;
  productName: string;
  quantity: number;
  subtotalFinalMinor: number;
}

export interface DriverHistoryEntry {
  id: string;
  kind: DriverOperationKind;
  label: string;
  /** Real instant of THIS operation (not of the order as a whole). */
  occurredAt: string;
  orderId: string | null;
  /** Last 6 chars of the order id, uppercase — for display. */
  orderReference: string | null;
  clientId: string | null;
  clientName: string | null;
  documentNumber: string | null;
  zona: string | null;
  origin: 'CITIZEN' | 'STAFF' | null;
  status: string | null;
  paymentMethod: 'ACCOUNT' | 'CASH' | null;
  /** Order total, when the operation settles a whole order. */
  totalFinalMinor: number | null;
  /** Sum of item quantities, when the operation settles a whole order. */
  units: number | null;
  /** Cash physically collected on this operation. */
  cashCollectedMinor: number;
  /** cta cte charge generated by this operation. */
  accountChargedMinor: number;
  /** cta cte charge annulled by this operation (cash flip or cancel). */
  accountReversedMinor: number;
  /** Free-text detail: cancellation reason, cash description, item summary. */
  detail: string | null;
  items: DriverHistoryItemRow[];
}

export interface DriverHistorySummary {
  operationCount: number;
  ordersClaimed: number;
  deliveriesStarted: number;
  ordersDelivered: number;
  directOrders: number;
  ordersCancelled: number;
  manualCashCollections: number;
  manualCashReversals: number;
  distinctClients: number;
  unitsDelivered: number;
  /** Sum of every order total closed in the period. */
  totalDeliveredMinor: number;
  /** Cash collected through orders + manual cash movements. */
  cashCollectedMinor: number;
  /** cta cte charges generated by orders. */
  accountChargedMinor: number;
  /** cta cte charges annulled in the period. */
  accountReversedMinor: number;
}

export interface DriverHistoryPeriodSummary {
  preset: ReportPeriodPreset;
  label: string;
  dateFrom: string;
  dateTo: string;
}

export interface DriverHistoryDriver {
  id: string;
  firstName: string;
  lastName: string;
  fullName: string;
}

export interface DriverHistory {
  period: DriverHistoryPeriodSummary;
  driver: DriverHistoryDriver;
  summary: DriverHistorySummary;
  /** Newest first. */
  operations: DriverHistoryEntry[];
  /** True when `operations` was cut at DRIVER_HISTORY_MAX_OPERATIONS. */
  truncated: boolean;
}